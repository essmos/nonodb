"""Outbox-style event producer and polling consumer for NonoDB.

The daemon does not emit read events. ``EventProducer`` writes an event in the
same atomic ``write_batch`` as application data, and ``EventConsumer`` polls the
event collection by sortable event ``_id``.

Delivery is at-least-once. Handlers must be idempotent, and consumers should
store a checkpoint only after successful processing.
"""

from __future__ import annotations

import logging
import os
import threading
import time
from typing import Any, Callable, Iterable, Mapping, Optional

logger = logging.getLogger(__name__)

_CROCKFORD = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"
_RANDOM_BITS = 80
_RANDOM_MAX = (1 << _RANDOM_BITS) - 1
_id_lock = threading.Lock()
_last_ms = 0
_last_random = 0


def now_ms() -> int:
    """Current UTC time as Unix milliseconds."""
    return int(time.time() * 1000)


def _encode_event_id(milliseconds: int, randomness: int) -> str:
    value = ((milliseconds & ((1 << 48) - 1)) << _RANDOM_BITS) | randomness
    chars = [""] * 26
    for index in range(25, -1, -1):
        chars[index] = _CROCKFORD[value & 31]
        value >>= 5
    return "".join(chars)


def new_event_id(milliseconds: Optional[int] = None) -> str:
    """Returns a lexicographically sortable ULID-style 26-character id.

    Ids generated by one process are monotonic even when several are created in
    the same millisecond.
    """
    global _last_ms, _last_random
    with _id_lock:
        ms = now_ms() if milliseconds is None else int(milliseconds)
        if ms <= _last_ms:
            ms = _last_ms
            _last_random += 1
            if _last_random > _RANDOM_MAX:
                ms += 1
                _last_random = 0
        else:
            _last_ms = ms
            _last_random = int.from_bytes(os.urandom(10), "big")
        return _encode_event_id(ms, _last_random)


def event_timestamp_ms(event_id: str) -> Optional[int]:
    """Extracts the millisecond timestamp from a 26-character event id."""
    if not isinstance(event_id, str) or len(event_id) != 26:
        return None
    value = 0
    for char in event_id[:10].upper():
        try:
            digit = _CROCKFORD.index(char)
        except ValueError:
            return None
        value = (value << 5) | digit
    return value


class EventProducer:
    """Writes events atomically with application data."""

    def __init__(
        self,
        events: Any,
        *,
        clock: Callable[[], int] = now_ms,
        id_factory: Callable[[], str] = new_event_id,
    ):
        self.events = events
        self._clock = clock
        self._id_factory = id_factory

    def emit(
        self,
        event_type: str,
        payload: Optional[Mapping[str, Any]] = None,
        *,
        doc_id: Optional[str] = None,
        data_ops: Optional[Iterable[Mapping[str, Any]]] = None,
        event_id: Optional[str] = None,
        metadata: Optional[Mapping[str, Any]] = None,
    ) -> str:
        """Atomically append an event and optional application writes.

        Every entry in ``data_ops`` must contain its own ``coll`` field. The
        event insert is appended to the same ``write_batch``, so either all
        writes commit or none do.
        """
        if not event_type:
            raise ValueError("event_type must not be empty")
        event = {
            "_id": event_id or self._id_factory(),
            "type": event_type,
            "payload": dict(payload or {}),
            "created_at": self._clock(),
        }
        if doc_id is not None:
            event["doc_id"] = doc_id
        if metadata is not None:
            event["metadata"] = dict(metadata)

        ops = list(data_ops or [])
        for op in ops:
            if "coll" not in op:
                raise ValueError("each data_ops entry must include coll")
        ops.append({"op": "insert", "coll": self.events.name, "doc": event})
        self.events.write_batch(ops)
        return event["_id"]


class EventConsumer:
    """Polls an event collection and stores a per-consumer checkpoint.

    Events are normally consumed immediately in ``_id`` order. A short overlap
    window re-scans events that aged past the high-water mark, so an event whose
    atomic write committed after a slightly newer event id is still delivered.
    """

    def __init__(
        self,
        events: Any,
        checkpoints: Any,
        consumer_id: str,
        *,
        clock: Callable[[], int] = now_ms,
        overlap_seconds: float = 2.0,
        late_scan_limit: int = 1000,
    ):
        if not consumer_id:
            raise ValueError("consumer_id must not be empty")
        if overlap_seconds < 0:
            raise ValueError("overlap_seconds must not be negative")
        if late_scan_limit < 1:
            raise ValueError("late_scan_limit must be at least 1")
        self.events = events
        self.checkpoints = checkpoints
        self.consumer_id = consumer_id
        self._clock = clock
        self._overlap_ms = int(overlap_seconds * 1000)
        self._late_scan_limit = late_scan_limit
        self._seen: dict[str, int] = {}
        self._late_cursor = ""
        self._late_cursor_loaded = False
        self._pending_late_target: Optional[str] = None
        self._pending_late_ids: set[str] = set()

    def _checkpoint_doc(self) -> dict[str, Any]:
        doc = self.checkpoints.find_one({"_id": self.consumer_id})
        return dict(doc) if doc else {}

    def checkpoint(self) -> str:
        """Returns the last successfully processed event id."""
        value = self._checkpoint_doc().get("last_id")
        return value if isinstance(value, str) else ""

    def _load_late_cursor(self, last_id: str, stored: Any) -> None:
        if self._late_cursor_loaded:
            return
        if isinstance(stored, str) and stored:
            self._late_cursor = stored
        elif last_id:
            last_ts = event_timestamp_ms(last_id)
            if last_ts is None:
                self._late_cursor = last_id
            else:
                floor_ms = max(0, last_ts - self._overlap_ms)
                self._late_cursor = _encode_event_id(floor_ms, 0)
        self._late_cursor_loaded = True

    def _prune_seen(self, now: int) -> None:
        if not self._seen:
            return
        expired = [event_id for event_id, until in self._seen.items() if until <= now]
        for event_id in expired:
            self._seen.pop(event_id, None)

    def fetch(
        self,
        *,
        limit: int = 100,
        types: Optional[Iterable[str]] = None,
    ) -> list[dict[str, Any]]:
        """Fetches the next events after the checkpoint, oldest first.

        The batch may also contain older events from the overlap window. Already
        delivered ids are filtered in-process; after a restart they are simply
        delivered again, which is allowed by the at-least-once contract.
        """
        if limit < 1:
            raise ValueError("limit must be at least 1")
        now = self._clock()
        self._prune_seen(now)
        doc = self._checkpoint_doc()
        last_id = doc.get("last_id")
        if not isinstance(last_id, str):
            last_id = ""
        self._load_late_cursor(last_id, doc.get("late_cursor"))
        self._pending_late_target = None
        self._pending_late_ids = set()

        fetched: list[dict[str, Any]] = []
        late_ids: set[str] = set()
        wanted = list(types) if types is not None else None

        if self._overlap_ms > 0 and last_id:
            last_ts = event_timestamp_ms(last_id)
            if last_ts is not None:
                boundary_id = _encode_event_id(max(0, now - self._overlap_ms), 0)
                target_id = boundary_id if boundary_id < last_id else last_id
                if self._late_cursor < target_id:
                    late_query: dict[str, Any] = {
                        "_id": {"$lte": target_id}
                    }
                    # Like the main query, never pass an empty string as an LMDB
                    # key bound. An empty late cursor means "from the beginning".
                    if self._late_cursor:
                        late_query["_id"]["$gt"] = self._late_cursor
                    if wanted:
                        late_query["type"] = {"$in": wanted}
                    late = self.events.find(
                        late_query,
                        sort=[("_id", 1)],
                        limit=self._late_scan_limit,
                    )
                    scanned_target = target_id
                    if len(late) >= self._late_scan_limit:
                        scanned_target = str(late[-1].get("_id") or target_id)
                    self._pending_late_target = scanned_target
                    for event in late:
                        event_id = event.get("_id")
                        if isinstance(event_id, str):
                            late_ids.add(event_id)
                    fetched.extend(late)

        # An empty string is not a valid LMDB key bound. A fresh consumer simply
        # starts from the beginning of the collection.
        query: dict[str, Any] = {} if not last_id else {"_id": {"$gt": last_id}}
        if wanted:
            query["type"] = {"$in": wanted}
        fetched.extend(self.events.find(query, sort=[("_id", 1)], limit=limit))

        unique: dict[str, dict[str, Any]] = {}
        for event in fetched:
            event_id = event.get("_id")
            if not isinstance(event_id, str):
                continue
            if event_id in self._seen or event_id in unique:
                continue
            unique[event_id] = event

        # Only unseen late events need to be acknowledged before the late cursor
        # can move. Seen or duplicate ids are already safe.
        self._pending_late_ids = late_ids & set(unique)
        return sorted(unique.values(), key=lambda event: str(event.get("_id")))

    def advance(self, events: Iterable[Mapping[str, Any]]) -> str:
        """Moves the checkpoint to the highest processed event id."""
        doc = self._checkpoint_doc()
        current = doc.get("last_id")
        if not isinstance(current, str):
            current = ""
        stored_late = doc.get("late_cursor")
        self._load_late_cursor(current, stored_late)

        processed_ids: set[str] = set()
        newest = current
        for event in events:
            event_id = event.get("_id")
            if not isinstance(event_id, str):
                continue
            processed_ids.add(event_id)
            if event_id > newest:
                newest = event_id

        late_cursor = self._late_cursor
        if self._pending_late_target is not None:
            if self._pending_late_ids <= processed_ids:
                if self._pending_late_target > late_cursor:
                    late_cursor = self._pending_late_target
        self._pending_late_target = None
        self._pending_late_ids = set()

        now = self._clock()
        expire = now + max(self._overlap_ms, 10_000)
        for event_id in processed_ids:
            self._seen[event_id] = expire

        stored_late_str = stored_late if isinstance(stored_late, str) else ""
        if newest == current and late_cursor == stored_late_str:
            return current
        self._late_cursor = late_cursor
        self.checkpoints.update(
            {"_id": self.consumer_id},
            {
                "$set": {
                    "last_id": newest,
                    "late_cursor": late_cursor,
                    "updated_at": now,
                }
            },
            upsert=True,
        )
        return newest

    def reset(self) -> None:
        """Deletes this consumer's checkpoint and starts from the beginning."""
        self.checkpoints.delete({"_id": self.consumer_id})
        self._seen.clear()
        self._late_cursor = ""
        self._late_cursor_loaded = False
        self._pending_late_target = None
        self._pending_late_ids = set()


class EventRunner:
    """Dispatch consumed events to Python handlers."""

    def __init__(self, consumer: EventConsumer, *, ignore_unknown: bool = True):
        self.consumer = consumer
        self.ignore_unknown = ignore_unknown
        self.handlers: dict[str, Callable[[dict[str, Any]], Any]] = {}
        self._stop = threading.Event()

    def register(
        self,
        event_type: str,
        handler: Callable[[dict[str, Any]], Any],
    ) -> None:
        if not event_type:
            raise ValueError("event_type must not be empty")
        self.handlers[event_type] = handler

    def stop(self) -> None:
        self._stop.set()

    def run_once(
        self,
        *,
        limit: int = 100,
        types: Optional[Iterable[str]] = None,
    ) -> int:
        """Processes one batch and returns the number of events advanced.

        The checkpoint stops before the first handler failure, so the failed
        event is retried on the next poll.
        """
        events = self.consumer.fetch(limit=limit, types=types)
        if not events:
            return 0
        processed: list[dict[str, Any]] = []
        for event in events:
            event_type = str(event.get("type") or "")
            handler = self.handlers.get(event_type)
            if handler is None:
                if not self.ignore_unknown:
                    logger.error("unknown event type %r for event %s", event_type, event.get("_id"))
                    break
                logger.warning("ignoring unknown event type %r", event_type)
                processed.append(event)
                continue
            try:
                handler(event)
            except Exception:  # noqa: BLE001 - handlers are user code
                logger.exception("event %s (%s) failed", event.get("_id"), event_type)
                break
            processed.append(event)
        self.consumer.advance(processed)
        return len(processed)

    def run_forever(
        self,
        *,
        poll_interval: float = 1.0,
        limit: int = 100,
        types: Optional[Iterable[str]] = None,
    ) -> None:
        if poll_interval <= 0:
            raise ValueError("poll_interval must be positive")
        if types is not None:
            types = tuple(types)
        while not self._stop.is_set():
            processed = self.run_once(limit=limit, types=types)
            if processed < limit:
                self._stop.wait(poll_interval)
